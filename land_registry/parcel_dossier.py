def _licence_status(entry: SourceCatalogEntry | None, reported: bool, locale: str) -> str:
    index = 1 if locale.startswith("en") else 0
    if entry is None:
        if reported:
            return (
                "Nessuna corrispondenza in catalogo; la licenza dichiarata non è stata verificata in modo indipendente",
                "No catalogue match; reported licence has not been independently reviewed",
            )[index]
        return (
            "Nessuna corrispondenza in catalogo; occorre verificare fornitore e licenza",
            "No catalogue match; provider and licence review required",
        )[index]
    pair = _LICENCE_STATUS.get(entry.license_basis, _LICENCE_STATUS["provider_terms_review_pending"])
    return pair[index]


def source_register_rows(source: Any, metadata: dict[str, Any], locale: str) -> list[list[str]]:
    """Catalogue data combined with response-specific provenance, without inventing vintages."""
    text = labels(locale)
    source_text = source if isinstance(source, str) and source.strip() else text["not_reported"]
    entry = find_source_catalog_entry(source_text)
    reported = metadata.get("license") or metadata.get("licence")
    catalogue_licence = entry.license_name if entry is not None else None
    missing = text["r_not_reported_meta"]
    rows = [
        [text["r_source"], source_text],
        [text["r_provider"], entry.display_name if entry else text["r_no_match"]],
        [text["r_url"], entry.provider_url if entry else text["r_not_available"]],
        [text["r_vintage"], str(metadata.get("data_vintage") or missing)],
        [text["r_dataset"], str(metadata.get("dataset_version") or metadata.get("data_vintage") or missing)],
        [text["r_model"], str(metadata.get("model_version") or missing)],
        [text["r_updated"], str(metadata.get("updated_at") or missing)],
        [text["r_licence"], str(reported or catalogue_licence or text["r_not_reported_meta"])],
        [text["r_licence_status"], _licence_status(entry, bool(reported), locale)],
    ]
    if entry is not None and entry.terms_url:
        rows.append([text["r_terms"], entry.terms_url])
    if entry is not None and entry.citation:
        rows.append([text["r_citation"], entry.citation])
    if entry is not None and entry.attribution_text:
        rows.append([text["r_attribution"], entry.attribution_text])
    return rows


def _provenance(source: Any, payload: dict[str, Any] | None, **extra: Any) -> dict[str, Any]:
    payload = payload or {}
    keys = ("dataset_version", "data_vintage", "model_version", "license", "licence", "updated_at")
    meta = {key: payload.get(key) for key in keys if payload.get(key)}
    meta.update({key: value for key, value in extra.items() if value})
    return {"source": source or payload.get("source"), "metadata": meta}


# -- inputs ---------------------------------------------------------------------------------------------------------


def representative_point(geometry: Any) -> tuple[float, float] | None:
    """(lat, lng) of a point inside the geometry, or ``None``."""
    try:
        from shapely.geometry import shape

        point = shape(geometry).representative_point()
        return float(point.y), float(point.x)
    except Exception:  # noqa: BLE001 - any malformed geometry simply has no point
        return None


async def _safe(awaitable: Awaitable[Any], name: str, timeout: float = SOURCE_TIMEOUT_SECONDS) -> Any:
    """Await one source; a failing or slow source degrades to ``None`` and never fails the report."""
    try:
        return await asyncio.wait_for(awaitable, timeout=timeout)
    except Exception as exc:  # noqa: BLE001
        log.warning("Dossier source %s unavailable: %s", name, exc)
        return None


async def gather_inputs(reference: str, parcel: dict[str, Any], *, neighbours: list[Any] | None = None) -> dict[str, Any]:
    """Collect every server-side source the dossier uses. Missing sources are ``None``."""
    from land_registry import stats_service

    props = parcel.get("properties") or {}
    geometry = parcel.get("geometry")
    code = str(props.get("municipality_code") or reference.split("_", 1)[0] or "").strip().upper()
    point = representative_point(geometry)
    municipality = await _safe(stats_service.aget_municipality_by_cadastral_code(code), "municipality") if code else None
    province_name = (municipality or {}).get("province") or props.get("province") or ""
    istat = (municipality or {}).get("istat_code") or (municipality or {}).get("procom")

    async def omi() -> tuple[Any, Any, Any]:
        if not point or not province_name:
            return None, None, None
        zone = await _safe(
            stats_service.aget_omi_zone_at_point(province_name, point[0], point[1], cadastral_code=code), "omi-zone"
        )
        code_zone = (zone or {}).get("zone")
        if not code_zone:
            return zone, None, None
        quotes, history = await asyncio.gather(
            _safe(stats_service.aget_omi_quotes(code, zona=code_zone), "omi-quotes"),
            _safe(asyncio.to_thread(stats_service.get_omi_history, code, code_zone), "omi-history"),
        )
        return zone, quotes, history

    async def risks_with_seismic() -> Any:
        risks = await _safe(asyncio.to_thread(stats_service.get_environmental_risks, istat), "risks")
        risks = dict(risks) if isinstance(risks, dict) else {"istat_code": str(istat), "seismic": None, "hydrogeological": None}
        if not risks.get("seismic"):
            risks["seismic"] = await _safe(stats_service.aget_seismic_by_istat_code(istat), "seismic")
        return risks

    async def census() -> Any:
        if not point:
            return None
        return await _safe(stats_service.aget_census_section_at_point(point[0], point[1], cadastral_code=code), "census")

    results = await asyncio.gather(
        omi(),
        census(),
        _safe(stats_service.aget_income_profile(code), "income") if code else _none(),
        risks_with_seismic() if istat else _none(),
        _safe(stats_service.aget_mps04_pga_at_point(*point), "mps04") if point else _none(),
        _safe(stats_service.aget_parcel_hazard_intersections(geometry), "hazards") if geometry else _none(),
        _safe(stats_service.aget_parcel_subsidence_intersections(geometry), "subsidence") if geometry else _none(),
        _safe(
            stats_service.aget_buildings_for_parcel(reference, cadastral_code=code, municipality=municipality), "buildings"
        ),
    )
    (zone, quotes, history), census_feature, income, risks, mps04, hazards, subsidence, buildings = results
    return {
        "reference": reference,
        "parcel": parcel,
        "neighbours": list(neighbours or [])[:NEIGHBOUR_LIMIT],
        "point": point,
        "municipality": municipality,
        "omi_zone": zone,
        "omi_quotes": quotes,
        "omi_history": history,
        "census": census_feature,
        "income": income,
        "risks": risks,
        "mps04": mps04,
        "hazards": hazards,
        "subsidence": subsidence,
        "buildings": buildings,
    }


async def _none() -> None:
    return None


# -- assembly -------------------------------------------------------------------------------------------------------

_RESIDENTIAL = re.compile(r"abitaz|civil|econom|vill|resid|apartment|home|house", re.IGNORECASE)
_CENSUS_AGE_COLUMNS = (
    ("<5", "p14"), ("5–9", "p15"), ("10–14", "p16"), ("15–19", "p17"), ("20–24", "p18"), ("25–29", "p19"),
    ("30–34", "p20"), ("35–39", "p21"), ("40–44", "p22"), ("45–49", "p23"), ("50–54", "p24"), ("55–59", "p25"),
    ("60–64", "p26"), ("65–69", "p27"), ("70–74", "p28"), ("75+", "p29"),
)
_SEISMIC_TONE = {1: "high", 2: "high", 3: "medium", 4: "low"}


def _kv(rows: list[list[str | None]]) -> dict[str, Any]:
    return {"type": "kv", "rows": [[label, value] for label, value in rows if value not in (None, "")]}


def _pick_quote(quotes: list[dict[str, Any]]) -> dict[str, Any] | None:
    for quote_row in quotes:
        if _RESIDENTIAL.search(str(quote_row.get("tipologia") or "")) and _number(quote_row.get("prezzo_min")) is not None:
            return quote_row
    return next((q for q in quotes if _number(q.get("prezzo_min")) is not None), None)


def _history_points(history: dict[str, Any] | None, state: str | None, limit: int = 24) -> list[dict[str, Any]]:
    rows = []
    for row in (history or {}).get("history") or []:
        low, high = _number(row.get("prezzo_min")), _number(row.get("prezzo_max"))
        row_state = str(row.get("stato_conservazione") or "").strip().upper()
        if low is None or high is None or (state and row_state and row_state != state.strip().upper()):
            continue
        rows.append(
            {
                "label": f"{row.get('anno')} S{row.get('semestre')}",
                "min": low,
                "max": high,
                "mid": (low + high) / 2,
                "rent_min": _number(row.get("locazione_min")),
                "rent_max": _number(row.get("locazione_max")),
            }
        )
    return rows[-limit:]


def build_dossier(
    inputs: dict[str, Any],
    *,
    locale: str = "it",
    report_id: str,
    now: datetime | None = None,
    page_url: str | None = None,
    saved: dict[str, Any] | None = None,
) -> tuple[dict[str, Any], dict[str, bytes]]:
    """Template variables and virtual files (SVG images) for one parcel. Pure: no I/O."""
    locale = "en" if str(locale).lower().startswith("en") else "it"
    text = labels(locale)
    now = now or datetime.now(UTC)
    parcel = inputs["parcel"]
    props = parcel.get("properties") or {}
    geometry = parcel.get("geometry")
    reference = inputs["reference"]
    municipality = inputs.get("municipality") or {}
    files: dict[str, bytes] = {}
    register: list[dict[str, Any]] = []

    area = _number(props.get("computed_area_sqm")) or _number(props.get("area_sqm"))
    perimeter = svg.geometry_perimeter_m(geometry)
    comune = props.get("municipality_name") or municipality.get("name") or ""
    comune_display = str(comune).title() if str(comune).isupper() else str(comune)
    province_code = props.get("province") or municipality.get("province_sigla") or ""
    sheet = props.get("sheet") or props.get("sheet_number") or props.get("foglio") or ""
    parcel_no = props.get("parcel") or props.get("parcel_number") or props.get("particella") or ""
    cadastral_code = props.get("municipality_code") or reference.split("_", 1)[0]
    region = props.get("region") or municipality.get("region") or ""
    region_display = str(region).title() if str(region).isupper() else str(region)

    # --- key figures
    quotes = (inputs.get("omi_quotes") or {}).get("quotes") or []
    picked = _pick_quote(quotes)
    omi_mid = None
    omi_range = None
    if picked:
        low, high = _number(picked.get("prezzo_min")), _number(picked.get("prezzo_max"))
        if low is not None and high is not None:
            omi_mid = (low + high) / 2
            omi_range = _range(low, high, locale)
    seismic_zone = ((inputs.get("risks") or {}).get("seismic") or {}).get("zone")
    census_props = (inputs.get("census") or {}).get("properties") or {}
    census_pop = _number(census_props.get("p1") if census_props.get("p1") is not None else census_props.get("pop21"))
    census_area = _number(census_props.get("area_sqm") or census_props.get("area_m2") or census_props.get("shape_area"))
    density = census_pop / (census_area / 1e6) if census_pop is not None and census_area else None
    buildings = inputs.get("buildings") or {}
    buildings_known = bool(buildings) and buildings.get("available") is not False
    buildings_found = buildings_known and int(buildings.get("count") or 0) > 0
    n_a = text["n_a"]
    kpis = [
        {"label": text["area"], "value": _fmt(area, locale, 0, "m²") or n_a},
        {"label": text["omi_price"], "value": _fmt(omi_mid, locale, 0) or n_a, "hint": omi_range},
        {"label": text["seismic"], "value": f"{seismic_zone}" if seismic_zone is not None else n_a},
        {"label": text["buildings"], "value": str(buildings.get("count")) if buildings_found else n_a},
        {"label": text["perimeter"], "value": _fmt(perimeter, locale, 0, "m") or n_a},
        {"label": text["density"], "value": _fmt(density, locale, 0) or n_a},
    ]

    # --- risk chips (state each dataset honestly)
    chips: list[dict[str, str]] = []
    if seismic_zone is not None:
        tone = _SEISMIC_TONE.get(int(seismic_zone), "medium") if str(seismic_zone).isdigit() else "medium"
        chips.append({"label": f"{text['seismic']} {seismic_zone}", "tone": tone})
    subsidence = inputs.get("subsidence") or {}
    if subsidence.get("available") and subsidence.get("matched"):
        cls = subsidence.get("dominant_class")
        if cls:
            chips.append({"label": f"{text['f_subsidence_class']}: {cls}", "tone": "info"})

    # --- map
    sections: list[dict[str, Any]] = []
    caption = f"{reference}" + (f" · {_fmt(area, locale, 0, 'm²')}" if area else "")
    map_svg = svg.locator_svg(geometry, inputs.get("neighbours"), 520.0, 250.0, caption=caption)
    cover_map = svg.locator_svg(geometry, inputs.get("neighbours"), 520.0, 200.0)
    if cover_map:
        files["cover_map.svg"] = cover_map.encode()
    map_blocks: list[dict[str, Any]] = []
    if map_svg:
        files["locator_map.svg"] = map_svg.encode()
        map_blocks.append({"type": "image", "file": "locator_map.svg", "caption": text["map_caption"]})
    else:
        map_blocks.append({"type": "unavailable", "text": text["unavailable"]})
    sections.append({"id": "map", "title": text["sec_map"], "blocks": map_blocks})

    # --- cadastral identity + location
    register.append(
        {
            "title": text["sec_cadastre"],
            **_provenance(
                f"Agenzia delle Entrate INSPIRE cadastral extract · {props.get('source_release')}"
                if props.get("source_release")
                else "Agenzia delle Entrate INSPIRE cadastral extract",
                {},
                dataset_version=props.get("source_release"),
            ),
        }
    )
    sections.append(
        {
            "id": "cadastre",
            "title": text["sec_cadastre"],
            "blocks": [
                _kv(
                    [
                        [text["f_reference"], str(props.get("national_cadastral_reference") or reference)],
                        [text["f_sheet"], str(sheet) or None],
                        [text["f_parcel"], str(parcel_no) or None],
                        [text["f_section"], str(props.get("urban_section") or "") or None],
                        [text["f_code"], str(cadastral_code) or None],
                        [text["f_area"], _fmt(area, locale, 1)],
                        [text["f_perimeter"], _fmt(perimeter, locale, 1)],
                        [text["f_release"], props.get("source_release")],
                        [text["f_inspire"], props.get("inspire_localid")],
                    ]
                )
            ],
        }
    )
    centroid = inputs.get("point")
    sections.append(
        {
            "id": "location",
            "title": text["sec_location"],
            "blocks": [
                _kv(
                    [
                        [text["f_municipality"], comune_display or None],
                        [text["f_province"], municipality.get("province")],
                        [text["f_province_code"], province_code or None],
                        [text["f_region"], region_display or None],
                        [text["f_istat"], str(municipality.get("istat_code") or "") or None],
                        [text["f_nuts3"], municipality.get("nuts3")],
                        [text["f_postcode"], str(municipality.get("postal_code") or municipality.get("cap") or "") or None],
                        [text["f_centroid"], f"{centroid[0]:.6f}, {centroid[1]:.6f}" if centroid else None],
                    ]
                )
            ],
        }
    )

    # --- buildings
    b_blocks: list[dict[str, Any]] = []
    if buildings_known and not buildings_found:
        # An empty SISTER cache is "no record", not "no buildings".
        b_blocks.append({"type": "unavailable", "text": text["buildings_none"]})
        register.append({"title": text["sec_buildings"], **_provenance(buildings.get("source"), buildings)})
    elif buildings_known:
        addresses = [a.get("address") if isinstance(a, dict) else a for a in (buildings.get("addresses") or [])]
        addresses = [str(a) for a in addresses if a][:8]
        b_blocks.append(
            _kv(
                [
                    [text["f_buildings_count"], str(buildings.get("count", 0))],
                    [text["f_land_count"], str(len(buildings.get("land") or []))],
                    [text["f_addresses"], "; ".join(addresses) or None],
                ]
            )
        )
        b_blocks.append({"type": "note", "text": text["buildings_note"]})
        register.append({"title": text["sec_buildings"], **_provenance(buildings.get("source"), buildings)})
    else:
        b_blocks.append({"type": "unavailable", "text": text["unavailable"]})
    sections.append({"id": "buildings", "title": text["sec_buildings"], "blocks": b_blocks})

    # --- risks
    r_rows: list[list[str | None]] = []
    risks = inputs.get("risks") or {}
    hydro = risks.get("hydrogeological") or {}
    if seismic_zone is not None:
        r_rows.append([text["f_seismic_zone"], str((risks.get("seismic") or {}).get("zone_label") or seismic_zone)])
    landslide = ((hydro.get("landslide") or {}).get("area_pct") or {})
    flood = ((hydro.get("flood") or {}).get("area_pct") or {})
    p34 = None
    if landslide:
        values = [_number(landslide.get("P3_high")), _number(landslide.get("P4_very_high"))]
        p34 = sum(v for v in values if v is not None) if any(v is not None for v in values) else None
    r_rows.append([text["f_landslide"], _pct(p34, locale, 1)])
    r_rows.append([text["f_flood"], _pct(flood.get("P2_medium_probability"), locale, 1)])
    mps04 = inputs.get("mps04") or {}
    pga = _number(mps04.get("pga_g") if mps04.get("pga_g") is not None else mps04.get("pga"))
    r_rows.append([text["f_pga"], _fmt(pga, locale, 3, "g") if mps04.get("available") else None])
    hazards = inputs.get("hazards") or {}
    if hazards.get("available"):
        land, flo = hazards.get("landslide") or {}, hazards.get("flood") or {}
        r_rows.append([text["f_hazard_landslide"], str(land.get("worst_class") or text["no_match"])])
        r_rows.append([text["f_hazard_flood"], str(flo.get("worst_class") or text["no_match"])])
        register.append({"title": text["sec_risks"], **_provenance(hazards.get("source"), hazards)})
    if subsidence.get("available") and subsidence.get("matched"):
        classes = subsidence.get("class_distribution") or []
        class_text = ", ".join(f"{c.get('class')} ({_pct(c.get('area_pct'), locale, 1)})" for c in classes) or subsidence.get("dominant_class")
        r_rows.append([text["f_subsidence_class"], str(class_text) if class_text else None])
        r_rows.append([text["f_subsidence_velocity"], _fmt(subsidence.get("mean_velocity_mm_per_year"), locale, 2, "mm/anno" if locale == "it" else "mm/yr")])
        register.append({"title": text["sec_risks"], **_provenance(subsidence.get("source"), subsidence)})
    if hydro:
        register.append({"title": text["sec_risks"], **_provenance(hydro.get("source"), hydro)})
    if mps04.get("available"):
        register.append({"title": text["sec_risks"], **_provenance(mps04.get("source"), mps04)})
    risk_blocks: list[dict[str, Any]] = [_kv(r_rows)]
    unavailable_notes = []
    if not hazards.get("available"):
        unavailable_notes.append(f"{text['hazard_parcel']}: {text['unavailable'].lower()}")
    if not (subsidence.get("available") and subsidence.get("matched")):
        unavailable_notes.append(f"{text['f_subsidence_class']}: {text['unavailable'].lower()}")
    if unavailable_notes:
        risk_blocks.append({"type": "unavailable", "text": " · ".join(unavailable_notes)})
    risk_blocks.append({"type": "note", "text": text["seismic_note"]})
    sections.append({"id": "risks", "title": text["sec_risks"], "blocks": risk_blocks})

    # --- population (census section)
    p_blocks: list[dict[str, Any]] = []
    if census_props:
        ratios = census_props.get("ratios") or {}

        def ratio(key: str) -> str | None:
            value = _number(ratios.get(key))
            return None if value is None else f"{format_number(value * 100 if value <= 1 else value, locale, 1)} %"

        p_blocks.append(
            _kv(
                [
                    [text["f_census_section"], str(census_props.get("sez21_id") or "") or None],
                    [text["f_residents_sec"], _fmt(census_pop, locale, 0)],
                    [text["density"], _fmt(density, locale, 1)],
                    [text["f_households"], _fmt(census_props.get("pf1") if census_props.get("pf1") is not None else census_props.get("fam21"), locale, 0)],
                    [text["f_dwellings"], _fmt(census_props.get("a8") if census_props.get("a8") is not None else census_props.get("abi21"), locale, 0)],
                    [text["f_res_buildings"], _fmt(census_props.get("e3") if census_props.get("e3") is not None else census_props.get("edi21"), locale, 0)],
                    [text["f_employment"], ratio("employment_rate_working_age")],
                    [text["f_tertiary"], ratio("education_tertiary_rate")],
                    [text["f_foreign"], ratio("foreign_resident_share")],
                    [text["f_vacant"], ratio("vacancy_rate")],
                    [text["f_hh_size"], _fmt(ratios.get("avg_household_size"), locale, 2)],
                ]
            )
        )
        ages = [(label, _number(census_props.get(key))) for label, key in _CENSUS_AGE_COLUMNS]
        age_svg = svg.column_chart_svg(ages, 520.0, 150.0, value_format=lambda v: format_number(v, locale, 0))
        if age_svg and any(v for _, v in ages):
            files["chart_age.svg"] = age_svg.encode()
            p_blocks.append({"type": "image", "file": "chart_age.svg", "caption": text["chart_age"]})
        p_blocks.append({"type": "note", "text": text["modelled_note"]})
        register.append({"title": text["sec_population"], **_provenance(inputs.get("census", {}).get("source"), inputs.get("census"))})
    else:
        p_blocks.append({"type": "unavailable", "text": text["unavailable"]})
    sections.append({"id": "population", "title": text["sec_population"], "blocks": p_blocks})

    # --- income
    income = inputs.get("income") or {}
    i_blocks: list[dict[str, Any]] = []
    if income:
        i_blocks.append(
            _kv(
                [
                    [text["f_income_year"], str(income.get("year") or "") or None],
                    [text["f_taxpayers"], _fmt(income.get("taxpayers"), locale, 0)],
                    [text["f_mean_income"], _fmt(income.get("mean_taxable_income_eur"), locale, 0, "€")],
                ]
            )
        )
        averages = income.get("income_reference_averages") or {}
        order = (
            ("municipality", text["income_municipality"]),
            ("province", text["income_province"]),
            ("region", text["income_region"]),
            ("nation", text["income_nation"]),
        )
        def average_label(key: str, label: str) -> str:
            name = str((averages.get(key) or {}).get("name") or "")
            if key == "nation" or not name or name.casefold() == label.casefold():
                return label if key == "nation" else (name.title() if name.isupper() else name) or label
            return f"{label} · {name.title() if name.isupper() else name}"

        avg_rows = [
            (average_label(key, label), _number((averages.get(key) or {}).get("mean_taxable_income_eur")))
            for key, label in order
            if averages.get(key)
        ]
        chart = svg.bar_chart_svg(avg_rows, 520.0, value_format=lambda v: format_number(v, locale, 0), highlight=0)
        if chart:
            files["chart_income_avg.svg"] = chart.encode()
            i_blocks.append({"type": "image", "file": "chart_income_avg.svg", "caption": text["chart_income_avg"]})
        dist = [(bracket_label(r.get("bracket")), _number(r.get("pct"))) for r in income.get("income_distribution") or []]
        dist_svg = svg.bar_chart_svg(dist, 520.0, value_format=lambda v: f"{format_number(v, locale, 1)} %")
        if dist_svg:
            files["chart_income_dist.svg"] = dist_svg.encode()
            i_blocks.append({"type": "image", "file": "chart_income_dist.svg", "caption": text["chart_income_dist"]})
        i_blocks.append({"type": "note", "text": text["income_note"]})
        register.append({"title": text["sec_income"], **_provenance(income.get("source"), income)})
    else:
        i_blocks.append({"type": "unavailable", "text": text["unavailable"]})
    sections.append({"id": "income", "title": text["sec_income"], "blocks": i_blocks})

    # --- OMI
    zone = inputs.get("omi_zone") or {}
    o_blocks: list[dict[str, Any]] = []
    if zone.get("matched") and zone.get("zone"):
        o_blocks.append(
            _kv([[text["f_zone"], f"{zone['zone']}" + (f" · {zone['description']}" if zone.get("description") else "")]])
        )
        table_rows = []
        range_rows = []
        for q in quotes[:16]:
            metrics = q.get("derived_metrics") or {}
            table_rows.append(
                [
                    str(q.get("tipologia") or ""),
                    str(q.get("stato_conservazione") or ""),
                    _range(q.get("prezzo_min"), q.get("prezzo_max"), locale) or "–",
                    _range(q.get("locazione_min"), q.get("locazione_max"), locale, 1) or "–",
                    _pct(metrics.get("gross_rental_yield_pct"), locale, 2) or "–",
                    _pct(metrics.get("zone_percentile_pct"), locale, 0) or "–",
                ]
            )
            range_rows.append((str(q.get("tipologia") or ""), _number(q.get("prezzo_min")), _number(q.get("prezzo_max"))))
        if table_rows:
            o_blocks.append(
                {
                    "type": "table",
                    "columns": [
                        {"title": text["f_type"], "align": "left", "width": "1fr"},
                        {"title": text["f_state"], "align": "left", "width": "16mm"},
                        {"title": text["f_sale"], "align": "right", "width": "30mm"},
                        {"title": text["f_rent"], "align": "right", "width": "28mm"},
                        {"title": text["f_yield"], "align": "right", "width": "18mm"},
                        {"title": text["f_percentile"], "align": "right", "width": "20mm"},
                    ],
                    "rows": table_rows,
                }
            )
            chart = svg.range_bar_chart_svg(range_rows, 520.0, value_format=lambda v: format_number(v, locale, 0)) if len(range_rows) > 1 else None
            if chart:
                files["chart_omi_range.svg"] = chart.encode()
                o_blocks.append({"type": "image", "file": "chart_omi_range.svg", "caption": text["chart_omi_range"]})
        points = _history_points(inputs.get("omi_history"), (picked or {}).get("stato_conservazione"))
        history_chart = svg.band_line_chart_svg(points, 520.0, 150.0, value_format=lambda v: format_number(v, locale, 0))
        if history_chart:
            files["chart_omi_history.svg"] = history_chart.encode()
            o_blocks.append({"type": "image", "file": "chart_omi_history.svg", "caption": text["chart_omi_history"]})
            o_blocks.append(
                {
                    "type": "table",
                    "columns": [
                        {"title": text["f_semester"], "align": "left", "width": "1fr"},
                        {"title": text["f_sale"], "align": "right", "width": "40mm"},
                        {"title": text["f_rent"], "align": "right", "width": "40mm"},
                    ],
                    "rows": [
                        [
                            p["label"],
                            _range(p["min"], p["max"], locale) or "–",
                            _range(p["rent_min"], p["rent_max"], locale, 1) or "–",
                        ]
                        for p in reversed(points[-12:])
                    ],
                }
            )
        if not history_chart:
            o_blocks.append({"type": "note", "text": text["history_none"]})
        o_blocks.append({"type": "note", "text": text["zone_note"]})
        register.append({"title": text["sec_omi"], **_provenance((inputs.get("omi_quotes") or {}).get("source") or zone.get("source"), inputs.get("omi_quotes"), model_version=(inputs.get("omi_quotes") or {}).get("derived_metrics_model"))})
    else:
        o_blocks.append({"type": "unavailable", "text": text["unavailable"]})
    sections.append({"id": "omi", "title": text["sec_omi"], "blocks": o_blocks})

    # --- source register
    sources = []
    seen: set[tuple[str, str]] = set()
    versions: list[str] = []
    for item in register:
        key = (str(item.get("source")), str(sorted((item.get("metadata") or {}).items())))
        if key in seen:
            continue
        seen.add(key)
        sources.append({"title": item["title"], "rows": source_register_rows(item.get("source"), item.get("metadata") or {}, locale)})
        meta = item.get("metadata") or {}
        version = "/".join(str(v) for v in (meta.get("dataset_version") or meta.get("data_vintage"), meta.get("model_version")) if v)
        if version:
            versions.append(f"{item['title']}={version}")

    personal: list[dict[str, Any]] = []
    if saved:
        tags = ", ".join(saved.get("tags") or [])
        personal.append(
            _kv(
                [
                    [text["f_label"], saved.get("label")],
                    [text["f_status"], saved.get("status_label") or saved.get("status")],
                    [text["f_priority"], str(saved["priority"]) if saved.get("priority") is not None else None],
                    [text["f_favorite"], text["yes"] if saved.get("is_favorite") else text["no"]],
                    [text["f_tags"], tags or None],
                    [text["f_notes"], saved.get("notes")],
                ]
            )
        )

    qr = svg.qr_svg(page_url) if page_url else None
    if qr:
        files["qr.svg"] = qr.encode()

    contents = [s["title"] for s in sections] + [text["sec_sources"]] + ([text["sec_personal"]] if personal else [])
    variables = {
        "locale": locale,
        "text": text,
        "report": {
            "id": report_id,
            "date": now.strftime("%d/%m/%Y" if locale == "it" else "%Y-%m-%d"),
            "timestamp": now.strftime("%Y-%m-%d %H:%M UTC"),
            "url": page_url or "",
        },
        "parcel": {
            "reference": reference,
            "municipality": comune_display,
            "province": province_code,
            "sheet": str(sheet),
            "parcel": str(parcel_no),
            "subline": " · ".join(
                part
                for part in (
                    f"{text['f_sheet']} {sheet}" if sheet else "",
                    f"{text['f_parcel']} {parcel_no}" if parcel_no else "",
                    region_display,
                )
                if part
            ),
        },
        "kpis": kpis,
        "chips": chips,
        "contents": contents,
        "has_cover_map": bool(cover_map),
        "has_qr": bool(qr),
        "not_replace_items": text["not_replace_items"].split("|"),
        "sections": sections,
        "sources": sources,
        "versions": "; ".join(versions) if versions else text["r_no_versions"],
        "personal": personal,
    }
    return variables, files


