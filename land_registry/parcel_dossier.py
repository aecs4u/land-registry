# -- formatting (ported from the ReportLab report) ------------------------------------------------------------------


def _number(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if number == number else None  # NaN


def format_number(value: Any, locale: str | None = None, decimals: int | None = None) -> str:
    """Group thousands with the locale's separators (``1.298,56`` for Italian, ``1,298.56`` otherwise)."""
    number = float(value)
    if decimals is None:
        decimals = 0 if number == int(number) else 2
    text = f"{number:,.{decimals}f}"
    if (locale or "it").lower().startswith("it"):
        text = text.replace(",", "\x00").replace(".", ",").replace("\x00", ".")
    return text


def _fmt(value: Any, locale: str, decimals: int | None = None, unit: str = "") -> str | None:
    number = _number(value)
    if number is None:
        return None
    return f"{format_number(number, locale, decimals)}{(' ' + unit) if unit else ''}"


def _fmt_scaled(value: Any, locale: str, unit: str, kilo_unit: str, mega_unit: str) -> str | None:
    """Format large municipal totals without changing their stated units."""
    number = _number(value)
    if number is None:
        return None
    if number >= 1_000_000:
        return _fmt(number / 1_000_000, locale, 1, mega_unit)
    if number >= 1_000:
        return _fmt(number / 1_000, locale, 1, kilo_unit)
    return _fmt(number, locale, 0, unit)


def _pct(value: Any, locale: str, decimals: int = 1) -> str | None:
    return _fmt(value, locale, decimals, "%")


def _range(low: Any, high: Any, locale: str, decimals: int = 0) -> str | None:
    lo, hi = _number(low), _number(high)
    if lo is None or hi is None:
        return None
    if lo == hi:
        return format_number(lo, locale, decimals)
    return f"{format_number(lo, locale, decimals)}–{format_number(hi, locale, decimals)}"


_BRACKET_PREFIX = {"over": "> ", "under": "< ", "le": "≤ "}


def bracket_label(raw: Any) -> str:
    """``10_15k`` → ``10–15 k€``, ``over_120k`` → ``> 120 k€``, ``le_0`` → ``≤ 0``."""
    text = str(raw)
    for prefix, symbol in _BRACKET_PREFIX.items():
        if text.startswith(prefix + "_"):
            text = symbol + text[len(prefix) + 1 :]
            break
    text = text.replace("_", "–")
    return text[:-1] + " k€" if text.endswith("k") else text


def profile_matches_parcel(parcel: dict[str, Any], profile: dict[str, Any] | None) -> bool:
    """Avoid attaching reference-keyed enrichment to a different duplicate polygon."""
    if not isinstance(profile, dict):
        return False
    modeled = profile.get("parcel")
    if not isinstance(modeled, dict):
        return False
    props, modeled_props = parcel.get("properties") or {}, modeled.get("properties") or {}
    parcel_id, modeled_id = parcel.get("id", props.get("id")), modeled.get("id", modeled_props.get("id"))
    if parcel_id is not None and modeled_id is not None:
        return str(parcel_id) == str(modeled_id)
    geometry, modeled_geometry = parcel.get("geometry"), modeled.get("geometry")
    if isinstance(geometry, dict) and isinstance(modeled_geometry, dict):
        try:
            from shapely.errors import ShapelyError
            from shapely.geometry import shape

            return shape(geometry).equals(shape(modeled_geometry))
        except (ShapelyError, TypeError, ValueError):
            return False
    return False


