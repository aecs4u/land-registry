"""Typst parcel dossier ("scheda tecnica particella").

This is the maintained PDF report. It replaces the ReportLab renderer in :mod:`land_registry.parcel_report`, which is
deprecated. The page structure follows the market-standard parcel data sheet (cover with locator map and key figures,
table of contents, summary, thematic sections, source register); the content is ours and stays evidence-first:

* every figure comes from a named section of the server read model and carries its source in the final register;
* a missing or unavailable dataset is stated as such, never rendered as zero or "low";
* nothing is fetched from the browser, so the PDF is reproducible from the parcel reference alone.

Valuable pieces carried over from the ReportLab implementation: locale-aware number formatting, parcel/profile
matching, the provenance register with catalogue licence status, the dataset version footer, the locator map and the
chart geometry (see :mod:`land_registry.parcel_dossier_svg`).

``build_dossier`` is a pure function of the gathered inputs, so it can be tested without a database; ``gather_inputs``
does the I/O; ``render_dossier_pdf`` compiles the Typst template with ``aecs4u-documents``.
"""

