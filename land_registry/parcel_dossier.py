_engine: Any = None


def _get_engine() -> Any:
    global _engine
    if _engine is None:
        from aecs4u_documents import DocumentEngine

        _engine = DocumentEngine(extra_templates_dir=TEMPLATES_DIR)
    return _engine


def new_report_id() -> str:
    return f"PR-{uuid.uuid4().hex[:12].upper()}"


async def render_dossier_pdf(variables: dict[str, Any], files: dict[str, bytes]) -> bytes:
    """Compile the Typst template to PDF bytes."""
    return await _get_engine().render(TEMPLATE_NAME, variables, extra_files=files)


def map_url(base_url: str, reference: str) -> str:
    return f"{base_url.rstrip('/')}/map?parcel={quote(reference, safe='')}"


