def source_register_rows(source: Any, metadata: dict[str, Any], locale: str) -> list[list[str]]:
    """Catalogue data combined with response-specific provenance, without inventing vintages."""
    text = labels(locale)
    source_text = source if isinstance(source, str) and source.strip() else text["not_reported"]
    entry = find_source_catalog_entry(source_text)
    reported = metadata.get("license") or metadata.get("licence")
    catalogue_licence = entry.license_name if entry is not None else None
    missing = text["r_not_reported_meta"]
    rows = [
        [text["r_source"], source_text],
        [text["r_provider"], entry.display_name if entry else text["r_no_match"]],
        [text["r_url"], entry.provider_url if entry else text["r_not_available"]],
        [text["r_vintage"], str(metadata.get("data_vintage") or missing)],
        [text["r_dataset"], str(metadata.get("dataset_version") or metadata.get("data_vintage") or missing)],
        [text["r_model"], str(metadata.get("model_version") or missing)],
        [text["r_updated"], str(metadata.get("updated_at") or missing)],
        [text["r_licence"], str(reported or catalogue_licence or text["r_not_reported_meta"])],
        [text["r_licence_status"], _licence_status(entry, bool(reported), locale)],
    ]
    if metadata.get("match_method"):
        rows.append([text["r_match_method"], str(metadata["match_method"])])
    if metadata.get("spatial_resolution"):
        rows.append([text["r_spatial_resolution"], str(metadata["spatial_resolution"])])
    if entry is not None and entry.terms_url:
        rows.append([text["r_terms"], entry.terms_url])
    if entry is not None and entry.citation:
        rows.append([text["r_citation"], entry.citation])
    if entry is not None and entry.attribution_text:
        rows.append([text["r_attribution"], entry.attribution_text])
    return rows


def _provenance(source: Any, payload: dict[str, Any] | None, **extra: Any) -> dict[str, Any]:
    payload = payload or {}
    keys = (
        "dataset_version", "data_vintage", "model_version", "license", "licence", "updated_at",
        "match_method", "spatial_resolution",
    )
    meta = {key: payload.get(key) for key in keys if payload.get(key)}
    meta.update({key: value for key, value in extra.items() if value})
    return {"source": source or payload.get("source"), "metadata": meta}


